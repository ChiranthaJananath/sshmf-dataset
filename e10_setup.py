#!/usr/bin/env python3
"""E10 setup, run on the controller as your normal user: SSH aliases and Docker contexts
for the emulated hosts started on the target by fleet_ex/up.sh.

Emulated host i is addressed like a real host named ex<i>, e.g. sshmf-ex001-ts (new SSH
session per call) and sshmf-ex001-cm (persistent master), so e9_controller.py runs
unchanged with --hosts ex001,ex002,...

  python3 e10_setup.py config --target ume --n 100   # aliases, contexts, then check
  python3 e10_setup.py check  --n 100                # check only
  python3 e10_setup.py clean  --n 100                # remove aliases and contexts
"""
import argparse
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

from sshmf.common import FMT, dk, load_config, name
from sshmf_setup import CONF_D, SSH_DIR, ensure_include, host_block, run

CONF = CONF_D / "sshmf-ex.conf"
KNOWN = SSH_DIR / "known_hosts_sshmf_ex"
CONTAINERS = ("sshmf-probe", "sshmf-victim", "sshmf-logs")


def hosts(n):
    return [f"ex{i:03d}" for i in range(1, n + 1)]


def cmd_config(cfg, t, n, base, user):
    ip = cfg["hosts"][t]["ts_ip"]
    kh = "UserKnownHostsFile ~/.ssh/known_hosts_sshmf_ex"
    no_cm = [kh, "ControlMaster no", "ControlPath none"]
    cm = [kh, "ControlMaster auto", "ControlPath ~/.ssh/cm-%C", "ControlPersist 10m"]
    blocks = []
    for i, h in enumerate(hosts(n), start=1):
        blocks += [host_block(name(h, "ts"), ip, base + i, user, no_cm),
                   host_block(name(h, "cm"), ip, base + i, user, cm)]
    ensure_include()
    CONF.write_text("# generated by e10_setup.py (emulated hosts)\n\n" + "\n".join(blocks))
    os.chmod(CONF, 0o600)
    if KNOWN.exists():
        KNOWN.unlink()  # emulated hosts get fresh host keys on every `up.sh up`
    print(f"wrote {CONF} ({n} hosts x 2 aliases)")
    for h in hosts(n):
        for v in ("ts", "cm"):
            c = name(h, v)
            run(["docker", "context", "rm", "-f", c], check=False, quiet=True)
            run(["docker", "context", "create", c, "--description", f"SSH-MF {v} path to emulated host {h}",
                 "--docker", f"host=ssh://{c}"], quiet=True)
    print(f"created {2 * n} Docker contexts")
    cmd_check(n)


def cmd_check(n):
    """Every emulated host must answer over SSH and run the three supervised containers."""
    q = "docker inspect -f '{{.State.Running}}' " + " ".join(CONTAINERS)

    def one(h):
        p = subprocess.run(["ssh", name(h, "ts"), q], capture_output=True, text=True)
        ok = p.returncode == 0 and p.stdout.split() == ["true"] * len(CONTAINERS)
        return h, ok, (p.stderr.strip() or p.stdout.strip()).replace("\n", " | ")[:100]

    with ThreadPoolExecutor(max_workers=10) as pool:
        res = list(pool.map(one, hosts(n)))
    bad = [(h, msg) for h, ok, msg in res if not ok]
    for h, msg in bad:
        print(f"  {name(h, 'ts')}: FAIL {msg}")
    for h in (hosts(n)[0], hosts(n)[-1]):   # the Docker CLI path, on the first and the last host
        p = run(dk(name(h, "cm"), "version", "--format", FMT), check=False, quiet=True)
        print(f"  context {name(h, 'cm')}: {'server ' + p.stdout.strip() if p.returncode == 0 else 'FAIL ' + p.stderr.strip()}")
        run(["ssh", "-O", "exit", name(h, "cm")], check=False, quiet=True)
    print(f"{n - len(bad)}/{n} emulated hosts ready")
    if bad:
        sys.exit(1)


def cmd_clean(n):
    for h in hosts(n):
        run(["ssh", "-O", "exit", name(h, "cm")], check=False, quiet=True)
        for v in ("ts", "cm"):
            run(["docker", "context", "rm", "-f", name(h, v)], check=False, quiet=True)
    for f in (CONF, KNOWN):
        if f.exists():
            f.unlink()
    print(f"removed the aliases and contexts of {n} emulated hosts")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["config", "check", "clean"])
    ap.add_argument("--target", default="ume", help="real host that runs the emulated fleet")
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--base-port", type=int, default=22000, help="as given to fleet_ex/up.sh")
    ap.add_argument("--user", default="exp")
    a = ap.parse_args()
    cfg = load_config()
    if a.target not in cfg["hosts"]:
        sys.exit(f"unknown target {a.target}")
    {"config": lambda: cmd_config(cfg, a.target, a.n, a.base_port, a.user),
     "check": lambda: cmd_check(a.n),
     "clean": lambda: cmd_clean(a.n)}[a.cmd]()


if __name__ == "__main__":
    main()
