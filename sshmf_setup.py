#!/usr/bin/env python3
"""One-time setup and checks, run on the controller as your normal user (not root).

  python3 sshmf_setup.py ssh-config  --target ume   # SSH aliases sshmf-ume-{ts,lan,cm}
  python3 sshmf_setup.py contexts    --target ume   # Docker contexts with the same names
  python3 sshmf_setup.py targets     --target ume   # sshmf-probe + deterministic sshmf-logs on target
  python3 sshmf_setup.py tls-context --target ume --certs ~/.sshmf/tls-ume
  python3 sshmf_setup.py fleet-ssh-config --target ume --n 50
  python3 sshmf_setup.py preflight   --target ume
"""
import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

from sshmf.common import FMT, dk, load_config, name, observe_only, probe_of

HOME = Path.home()
SSH_DIR = HOME / ".ssh"
CONF_D = SSH_DIR / "config.d"
INCLUDE = "Include ~/.ssh/config.d/sshmf-*.conf"
PAD = "x" * 91  # "%07d " (8 B) + 91 B + "\n" = 100 B per line


def run(argv, check=True, quiet=False):
    p = subprocess.run(argv, capture_output=True, text=True)
    if not quiet:
        print("$", " ".join(argv) if isinstance(argv, list) else argv)
    if check and p.returncode != 0:
        sys.exit(f"failed: {p.stderr.strip() or p.stdout.strip()}")
    return p


def ensure_include():
    SSH_DIR.mkdir(mode=0o700, exist_ok=True)
    CONF_D.mkdir(mode=0o700, exist_ok=True)
    cfg = SSH_DIR / "config"
    old = cfg.read_text() if cfg.exists() else ""
    if INCLUDE not in old:
        if old:
            (SSH_DIR / "config.bak-sshmf").write_text(old)
        # Include must precede any Host block, so it goes first.
        cfg.write_text(INCLUDE + "\n\n" + old)
        os.chmod(cfg, 0o600)
        print(f"added Include line to {cfg} (backup: config.bak-sshmf)")


def host_block(alias, hostname, port, user, extra):
    lines = [f"Host {alias}", f"  HostName {hostname}", f"  Port {port}", f"  User {user}",
             "  BatchMode yes", "  ConnectTimeout 30", "  StrictHostKeyChecking accept-new"]
    return "\n".join(lines + [f"  {x}" for x in extra]) + "\n"


def cmd_ssh_config(cfg, t):
    h = cfg["hosts"][t]
    u, port = h.get("ssh_user", cfg["ssh"]["user"]), h.get("ssh_port", cfg["ssh"]["port"])
    no_cm = ["ControlMaster no", "ControlPath none"]
    cm = ["ControlMaster auto", "ControlPath ~/.ssh/cm-%C", "ControlPersist 10m"]
    # Client-side tuning only: classic ECDH key exchange instead of the post-quantum
    # hybrid default, and no GSSAPI attempt. Nothing changes on the target.
    tuned = no_cm + ["KexAlgorithms curve25519-sha256", "GSSAPIAuthentication no"]
    blocks = [host_block(name(t, "ts"), h["ts_ip"], port, u, no_cm)]
    if h.get("lan_ip"):
        blocks.append(host_block(name(t, "lan"), h["lan_ip"], port, u, no_cm))
    blocks += [host_block(name(t, "cm"), h["ts_ip"], port, u, cm),
               host_block(name(t, "tuned"), h["ts_ip"], port, u, tuned)]
    text = "# generated by sshmf_setup.py\n\n" + "\n".join(blocks)
    ensure_include()
    path = CONF_D / f"sshmf-{t}.conf"
    path.write_text(text)
    os.chmod(path, 0o600)
    print(f"wrote {path}")
    for v in ("ts", "lan", "cm", "tuned"):
        if v == "lan" and not h.get("lan_ip"):
            continue
        p = run(["ssh", name(t, v), "true"], check=False)
        print(f"  {name(t, v)}: {'OK' if p.returncode == 0 else 'FAIL ' + p.stderr.strip()}")


def expected_daemon(cfg, t):
    return cfg["hosts"][t].get("daemon_name", t)


def daemon_host(context):
    """Hostname of the daemon a context actually reaches (catches a remote CLI whose
    current context forwards dial-stdio to yet another host)."""
    p = run(dk(context, "info", "--format", "{{.Name}}"), check=False, quiet=True)
    return p.stdout.strip() if p.returncode == 0 else None


def cmd_contexts(cfg, t):
    wrong = []
    for v in ("ts", "lan", "cm", "tuned"):
        if v == "lan" and not cfg["hosts"][t].get("lan_ip"):
            continue
        c = name(t, v)
        run(["docker", "context", "rm", "-f", c], check=False, quiet=True)
        run(["docker", "context", "create", c, "--description", f"SSH-MF {v} path to {t}",
             "--docker", f"host=ssh://{c}"])
        p = run(dk(c, "version", "--format", FMT), check=False, quiet=True)
        if p.returncode != 0:
            print(f"  {c}: FAIL {p.stderr.strip()}")
            continue
        h = daemon_host(c)
        print(f"  {c}: server {p.stdout.strip()} on daemon host '{h}'")
        if h != expected_daemon(cfg, t):
            wrong.append(c)
    if wrong:
        sys.exit(f"contexts {wrong} reach daemon host != '{expected_daemon(cfg, t)}'. On {t}, run "
                 f"`docker context show`; if it is not 'default', run `docker context use default`.")


def cmd_targets(cfg, t):
    if observe_only(cfg, t):
        sys.exit(f"{t} is observe-only: nothing is created there")
    c = cfg["containers"]
    d = dk(name(t, "ts"))
    run(d + ["rm", "-f", c["probe"], c["logs"]], check=False)
    run(d + ["run", "-d", "--name", c["probe"], "--label", "sshmf=1", c["image"], "sleep", "infinity"])
    n = c["log_lines"]
    gen = f"awk 'BEGIN{{for(i=0;i<{n};i++) printf \"%07d {PAD}\\n\", i}}'; sleep infinity"
    run(d + ["run", "-d", "--name", c["logs"], "--label", "sshmf=1",
             "--log-driver", "json-file", "--log-opt", "max-size=2g", "--log-opt", "max-file=1",
             c["image"], "sh", "-c", gen])
    want = f"{n - 1:07d} {PAD}"
    for _ in range(120):
        p = run(d + ["logs", "--tail", "1", c["logs"]], check=False, quiet=True)
        if p.stdout.strip() == want:
            print(f"  {c['logs']}: {n} lines x 100 B ready")
            return
        time.sleep(5)
    sys.exit("log generator did not finish within 10 min")


def cmd_tls_context(cfg, t, certs):
    certs = Path(certs).expanduser()
    for f in ("ca.pem", "cert.pem", "key.pem"):
        if not (certs / f).exists():
            sys.exit(f"missing {certs / f}; copy it from the target first (see setup/tls_proxy.sh)")
    c = name(t, "tls")
    run(["docker", "context", "rm", "-f", c], check=False, quiet=True)
    host = f"tcp://{cfg['hosts'][t]['ts_ip']}:{cfg['tls']['port']}"
    run(["docker", "context", "create", c, "--description", f"SSH-MF mTLS proxy on {t}", "--docker",
         f"host={host},ca={certs / 'ca.pem'},cert={certs / 'cert.pem'},key={certs / 'key.pem'}"])
    p = run(dk(c, "version", "--format", FMT), check=False, quiet=True)
    print(f"  {c}: {'server ' + p.stdout.strip() if p.returncode == 0 else 'FAIL ' + p.stderr.strip()}")


def cmd_fleet_ssh_config(cfg, t, n):
    ip, base = cfg["hosts"][t]["ts_ip"], cfg["fleet"]["base_port"]
    extra = ["UserKnownHostsFile ~/.ssh/known_hosts_sshmf_fleet", "ControlMaster no", "ControlPath none"]
    text = "# generated by sshmf_setup.py (fleet)\n\n" + "\n".join(
        host_block(f"sshmf-fleet-{i:02d}", ip, base + i, "root", extra) for i in range(1, n + 1))
    ensure_include()
    path = CONF_D / "sshmf-fleet.conf"
    path.write_text(text)
    os.chmod(path, 0o600)
    kh = SSH_DIR / "known_hosts_sshmf_fleet"
    if kh.exists():
        kh.unlink()  # fleet containers get fresh host keys on every `fleet.sh up`
    print(f"wrote {path}")
    for i in (1, n):
        p = run(["docker", "-H", f"ssh://sshmf-fleet-{i:02d}", "version", "--format", FMT],
                check=False, quiet=True)
        print(f"  sshmf-fleet-{i:02d}: {'OK ' + p.stdout.strip() if p.returncode == 0 else 'FAIL ' + p.stderr.strip()}")


def cmd_preflight(cfg, t):
    ts = name(t, "ts")
    results = []

    def check(label, cmd, ok=lambda p: p.returncode == 0, level="FAIL"):
        p = subprocess.run(cmd, shell=True, capture_output=True, text=True)
        out = (p.stdout + p.stderr).strip().replace("\n", " | ")[:110]
        results.append(("PASS" if ok(p) else level, label, out))

    check("not running as root", "id -u", lambda p: p.stdout.strip() != "0")
    check("ssh alias ts has no multiplexing", f"ssh -G {ts} | grep -i '^controlmaster'",
          lambda p: "false" in p.stdout or " no" in p.stdout)
    check("ssh alias cm multiplexes", f"ssh -G {name(t, 'cm')} | grep -i '^controlmaster'",
          lambda p: "auto" in p.stdout)
    obs, want = observe_only(cfg, t), expected_daemon(cfg, t)
    for v in ("ts", "lan", "cm", "tuned"):
        opt = v in ("lan", "tuned")
        check(f"context {name(t, v)} reaches daemon '{want}'" + (" (optional)" if opt else ""),
              f"docker --context {name(t, v)} info --format '{{{{.Name}}}}'",
              lambda p: p.returncode == 0 and p.stdout.strip() == want,
              level="WARN" if opt else "FAIL")
    check(f"{t}: remote docker CLI uses context 'default'", f"ssh {ts} docker context show",
          lambda p: p.stdout.strip() == "default")
    check("local docker socket (curl)", "curl -sS --unix-socket /var/run/docker.sock http://localhost/_ping")
    check("target: curl + docker socket (optional on observe-only)",
          f"ssh {ts} \"curl -sS --unix-socket /var/run/docker.sock http://localhost/_ping\"",
          level="WARN" if obs else "FAIL")
    if obs:
        check(f"observe-only probe container '{probe_of(cfg, t)}' running",
              f"docker --context {ts} inspect -f '{{{{.State.Running}}}}' {probe_of(cfg, t) or 'UNSET'}",
              lambda p: p.stdout.strip() == "true")
    else:
        check(f"context {name(t, 'tls')} (optional, E4)",
              f"docker --context {name(t, 'tls')} version --format '{FMT}'", level="WARN")
        check("target: python3 >= 3.11",
              f"ssh {ts} \"python3 -c 'import sys; assert sys.version_info >= (3, 11); print(sys.version.split()[0])'\"")
        for c in (cfg["containers"]["probe"], cfg["containers"]["logs"]):
            check(f"target container {c} running",
                  f"docker --context {ts} inspect -f '{{{{.State.Running}}}}' {c}",
                  lambda p: p.stdout.strip() == "true")
    if cfg["hosts"][t].get("tailnet", True):
        check("tailscale path is direct", f"tailscale ping -c 1 {cfg['hosts'][t]['ts_ip']}",
              lambda p: "via DERP" not in p.stdout and p.returncode == 0)
    check("local NTP synchronised", "timedatectl show -p NTPSynchronized --value",
          lambda p: p.stdout.strip() == "yes", level="WARN")
    check("target NTP synchronised", f"ssh {ts} timedatectl show -p NTPSynchronized --value",
          lambda p: p.stdout.strip() == "yes", level="WARN")
    check("target fail2ban inactive (E8 single)", f"ssh {ts} systemctl is-active fail2ban",
          lambda p: p.stdout.strip() != "active", level="WARN")
    check("target sshd MaxStartups (default 10:30:100)",
          f"ssh {ts} \"grep -hi '^MaxStartups' /etc/ssh/sshd_config /etc/ssh/sshd_config.d/*.conf 2>/dev/null || echo default\"",
          level="WARN")
    check("no netem active on tailscale0", "tc qdisc show dev tailscale0",
          lambda p: "netem" not in p.stdout, level="WARN")
    check("local load1 < 2", "cat /proc/loadavg",
          lambda p: float(p.stdout.split()[0]) < 2, level="WARN")
    check("target load1 < 2", f"ssh {ts} cat /proc/loadavg",
          lambda p: p.returncode == 0 and float(p.stdout.split()[0]) < 2, level="WARN")

    width = max(len(r[1]) for r in results)
    for status, label, out in results:
        print(f"[{status}] {label.ljust(width)}  {out}")
    if any(r[0] == "FAIL" for r in results):
        sys.exit(1)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["ssh-config", "contexts", "targets", "tls-context",
                                    "fleet-ssh-config", "preflight"])
    ap.add_argument("--target", default="ume")
    ap.add_argument("--certs")
    ap.add_argument("--n", type=int, default=50)
    a = ap.parse_args()
    cfg = load_config()
    if a.target not in cfg["hosts"]:
        sys.exit(f"unknown target {a.target}")
    {"ssh-config": lambda: cmd_ssh_config(cfg, a.target),
     "contexts": lambda: cmd_contexts(cfg, a.target),
     "targets": lambda: cmd_targets(cfg, a.target),
     "tls-context": lambda: cmd_tls_context(cfg, a.target, a.certs or f"~/.sshmf/tls-{a.target}"),
     "fleet-ssh-config": lambda: cmd_fleet_ssh_config(cfg, a.target, a.n),
     "preflight": lambda: cmd_preflight(cfg, a.target)}[a.cmd]()


if __name__ == "__main__":
    main()
